Key Difference for iOS Testing

Since you mentioned cross-platform development for iOS, keep in mind that Apple does not allow direct .apk style sideloading without hurdles:

To distribute to family on iOS before going to the App Store, you will eventually need an Apple Developer Account ($99/year) to use TestFlight.

Alternatively, for direct personal device testing, you can plug an iPhone into a Mac and run the app directly through Xcode for free.