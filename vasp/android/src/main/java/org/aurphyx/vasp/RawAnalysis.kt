    val hookStrength: Double? = null,
    val melodicMotion: String? = null,
    val referencePitch: String? = null,
    val microtonality: String? = null,
    val explicitFilter: String? = null,
    val topicClusters: List<String> = emptyList(),
    val narrativeArc: String? = null,
    val vocalPosition: String? = null,
    val deliveryStyle: String? = null,
    val vocalProcessing: String? = null,
