    val timelessnessScore: Double? = null,
    val sampleLineage: List<String> = emptyList(),
    val interpolation: List<String> = emptyList(),
    val genreTree: String? = null,
    val subcultureId: String? = null,
    val authenticityScore: Double? = null,
    val viralVelocity: String? = null,
