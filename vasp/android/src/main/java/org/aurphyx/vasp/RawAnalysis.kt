    val bpm: Double,
    val attackMs: Double,
    val centroidHz: Double,
    val keyMode: String,
    val sentimentScore: Double,
    val rmsAmplitude: Double,
    val dominantFreqHz: Double,
    val title: String? = null,
    val artist: String? = null,
    val isrc: String? = null,
    val sourceDna: String? = null,
    val keySignature: String? = null,
    val bpmPerceived: String? = null,
    val grooveQuantization: String? = null,
    val timeSignature: String? = null,
    val sectionalMarkers: List<String> = emptyList(),
    val mixWindowIndex: Double? = null,
    val breakdownDepth: Double? = null,
    val syncopationIndex: Double? = null,
    val ghostNoteDensity: Double? = null,
    val subDominant: Double? = null,
    val midForward: Double? = null,
    val airBrilliance: Double? = null,
    val spectralSaturation: Double? = null,
    val fidelityScore: String? = null,
    val dynamicRangeLra: Double? = null,
    val spatialWidth: String? = null,
    val textureSurface: String? = null,
    val textureArtifacts: String? = null,
    val moodStability: String? = null,
    val catharsisPotential: Double? = null,
    val nostalgiaTrigger: Double? = null,
    val buildUpVelocity: Double? = null,
